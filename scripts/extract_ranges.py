#!/usr/bin/env python3
"""Extract the preflop ranges of the Kill Tilt "Ranges Expresso" PDF into JSON.

The PDF is generated by WeasyPrint: every hand of a 13x13 grid is a filled
vector rectangle whose colour identifies the action, and every legend entry is
a small square swatch of the same colour followed by the action label.

The extraction reads those vector objects directly (no OCR, no guessing):
  * each grid cell must contain exactly the expected hand label,
  * each cell colour must match exactly one legend swatch,
  * each legend label must be a known action (see ACTIONS below),
otherwise the script fails loudly instead of producing plausible data.

Usage:  python3 scripts/extract_ranges.py [pdf] [output.json]
Requires: pdfplumber (pip install pdfplumber)
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

import pdfplumber

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PDF = ROOT / "Ranges_Expresso_KillTilt (1).pdf"
DEFAULT_OUT = ROOT / "src" / "data" / "ranges.json"

RANKS = "AKQJT98765432"

# Normalised legend label -> canonical action.  Labels that only differ by
# case or by the "NAI" abbreviation (= "non all-in") share the same id.
ACTIONS: dict[str, dict[str, str]] = {
    "fold": {"id": "fold", "label": "Fold"},
    "check back": {"id": "check", "label": "Check"},
    "call": {"id": "call", "label": "Call"},
    "open shove": {"id": "shove", "label": "Open shove"},
    "minraise / call": {"id": "minraise-call", "label": "Minraise / Call"},
    "minraise / fold": {"id": "minraise-fold", "label": "Minraise / Fold"},
    "3x / call": {"id": "raise3x-call", "label": "3x / Call"},
    "3x / fold": {"id": "raise3x-fold", "label": "3x / Fold"},
    "limp / call": {"id": "limp-call", "label": "Limp / Call"},
    "limp / fold": {"id": "limp-fold", "label": "Limp / Fold"},
    "limp / reraise": {"id": "limp-reraise", "label": "Limp / Reraise"},
    "limp/call vs 3bet, fold sinon": {
        "id": "limp-call-vs-3bet",
        "label": "Limp / Call vs 3bet, fold sinon",
    },
    "limp/call vs 2.5x, fold sinon": {
        "id": "limp-call-vs-2.5x",
        "label": "Limp / Call vs 2.5x, fold sinon",
    },
    "limp/reraise vs 2.5x": {
        "id": "limp-reraise-vs-2.5x",
        "label": "Limp / Reraise vs 2.5x",
    },
    "3bet all-in": {"id": "3bet-allin", "label": "3bet All-in"},
    "3bet non all in / call": {"id": "3bet-nai-call", "label": "3bet non all-in / Call"},
    "3bet nai / call": {"id": "3bet-nai-call", "label": "3bet non all-in / Call"},
    "3bet non all in / fold": {"id": "3bet-nai-fold", "label": "3bet non all-in / Fold"},
    "iso / call": {"id": "iso-call", "label": "Iso / Call"},
    "iso / fold": {"id": "iso-fold", "label": "Iso / Fold"},
    "iso all-in": {"id": "iso-allin", "label": "Iso All-in"},
    "profil dépendant": {"id": "profile-dependent", "label": "Profil dépendant"},
}

# Spot title (as printed on the page) -> structured context.
SPOTS: dict[tuple[str, str], dict[str, str]] = {
    ("3-MAX", "BTN"): {"spot": "btn-open", "hero": "BTN", "villain": ""},
    ("3-MAX", "SB vs BTN"): {"spot": "sb-vs-btn", "hero": "SB", "villain": "BTN"},
    ("3-MAX", "SB vs BB"): {"spot": "sb-open", "hero": "SB", "villain": "BB"},
    ("3-MAX", "BB vs SB"): {"spot": "bb-vs-sb", "hero": "BB", "villain": "SB"},
    ("HEADS-UP", "HU SB"): {"spot": "sb", "hero": "SB", "villain": "BB"},
    ("HEADS-UP", "HU BB"): {"spot": "bb", "hero": "BB", "villain": "SB"},
}

# Suffix of "RANGE — 25BB VS MINRAISE" -> what happened before hero acts.
SCENARIOS = {
    "": "open",
    "VS MINRAISE": "vs-minraise",
    "VS OPEN": "vs-open",
    "VS OPEN SHOVE": "vs-shove",
    "VS SHOVE": "vs-shove",
    "VS LIMP": "vs-limp",
}


class ExtractionError(RuntimeError):
    pass


def hand_at(row: int, col: int) -> str:
    if row == col:
        return RANKS[row] * 2
    if col > row:
        return RANKS[row] + RANKS[col] + "s"
    return RANKS[col] + RANKS[row] + "o"


def rgb_hex(color) -> str:
    if not isinstance(color, (tuple, list)) or len(color) != 3:
        raise ExtractionError(f"unexpected colour {color!r}")
    return "#" + "".join(f"{round(c * 255):02x}" for c in color)


def centre(obj) -> tuple[float, float]:
    return (obj["x0"] + obj["x1"]) / 2, (obj["top"] + obj["bottom"]) / 2


def inside(point, box) -> bool:
    x, y = point
    return box["x0"] <= x <= box["x1"] and box["top"] <= y <= box["bottom"]


def parse_page(page, page_no: int) -> dict:
    words = page.extract_words(keep_blank_chars=False, use_text_flow=False)
    lines = page.extract_text_lines()

    # --- header ---------------------------------------------------------
    header = [l["text"].strip() for l in lines if l["top"] < 180 and l["x0"] < 500]
    fmt = next((t for t in header if t in ("3-MAX", "HEADS-UP")), None)
    if fmt is None:
        raise ExtractionError(f"p{page_no}: format tag not found in {header}")
    idx = header.index(fmt)
    title, subtitle = header[idx + 1], header[idx + 2]
    range_line = next((l["text"] for l in lines if l["text"].startswith("RANGE")), None)
    m = re.fullmatch(r"RANGE\s+—\s+(\d+)BB\s*(.*)", range_line or "")
    if not m:
        raise ExtractionError(f"p{page_no}: cannot parse range line {range_line!r}")
    stack = int(m.group(1))
    scenario_label = m.group(2).strip()
    if scenario_label not in SCENARIOS:
        raise ExtractionError(f"p{page_no}: unknown scenario {scenario_label!r}")
    spot = SPOTS.get((fmt, title))
    if spot is None:
        raise ExtractionError(f"p{page_no}: unknown spot {(fmt, title)}")

    # --- legend ---------------------------------------------------------
    swatches = sorted(
        (r for r in page.rects if round(r["width"]) == 12 and round(r["height"]) == 12),
        key=lambda r: r["top"],
    )
    if not swatches:
        raise ExtractionError(f"p{page_no}: no legend swatch")
    legend = []
    for sw in swatches:
        _, cy = centre(sw)
        label_words = sorted(
            (
                w
                for w in words
                if w["x0"] > sw["x1"] and w["x0"] < sw["x1"] + 260 and abs(centre(w)[1] - cy) < 4
            ),
            key=lambda w: w["x0"],
        )
        label = " ".join(w["text"] for w in label_words).strip()
        key = re.sub(r"\s+", " ", label.lower())
        action = ACTIONS.get(key)
        if action is None:
            raise ExtractionError(f"p{page_no}: unknown legend label {label!r}")
        color = rgb_hex(sw["non_stroking_color"])
        if any(e["sourceColor"] == color for e in legend):
            raise ExtractionError(f"p{page_no}: two legend entries share colour {color}")
        if any(e["id"] == action["id"] for e in legend):
            raise ExtractionError(f"p{page_no}: duplicated action {action['id']}")
        legend.append({**action, "sourceLabel": label, "sourceColor": color})

    # --- grid -----------------------------------------------------------
    cells = [r for r in page.rects if round(r["width"]) == 33 and round(r["height"]) == 27]
    if len(cells) != 169:
        raise ExtractionError(f"p{page_no}: expected 169 grid cells, found {len(cells)}")
    cells.sort(key=lambda r: (round(r["top"]), r["x0"]))
    by_color = {e["sourceColor"]: e["id"] for e in legend}
    hands: dict[str, str] = {}
    for i, cell in enumerate(cells):
        row, col = divmod(i, 13)
        expected = hand_at(row, col)
        texts = [w["text"] for w in words if inside(centre(w), cell)]
        if texts != [expected]:
            raise ExtractionError(f"p{page_no}: cell {row},{col} reads {texts}, expected {expected}")
        color = rgb_hex(cell["non_stroking_color"])
        if color not in by_color:
            raise ExtractionError(f"p{page_no}: {expected} colour {color} not in legend")
        hands[expected] = by_color[color]

    # Rows must be well aligned: 13 distinct tops, 13 cells each.
    tops = sorted({round(c["top"]) for c in cells})
    if len(tops) != 13:
        raise ExtractionError(f"p{page_no}: grid rows misaligned ({len(tops)} rows)")

    fmt_id = "3max" if fmt == "3-MAX" else "hu"
    scenario = SCENARIOS[scenario_label]
    return {
        "id": f"{fmt_id}-{spot['spot']}-{stack}",
        "format": fmt_id,
        "spot": spot["spot"],
        "hero": spot["hero"],
        "villain": spot["villain"] or None,
        "stackBb": stack,
        "scenario": scenario,
        "title": title,
        "subtitle": subtitle,
        "scenarioLabel": scenario_label or None,
        "source": {"page": page_no},
        "actions": [
            {k: e[k] for k in ("id", "label", "sourceLabel", "sourceColor")} for e in legend
        ],
        # Every cell of this document is a single solid colour: one action at
        # 100 %.  Frequencies are kept explicit so mixed strategies can be
        # represented if another source provides them.
        "hands": {h: {a: 1} for h, a in hands.items()},
    }


def main() -> int:
    pdf_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PDF
    out_path = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    digest = hashlib.sha256(pdf_path.read_bytes()).hexdigest()
    ranges = []
    with pdfplumber.open(pdf_path) as pdf:
        title = (pdf.metadata or {}).get("Title", "")
        for page_no, page in enumerate(pdf.pages, start=1):
            text = page.extract_text() or ""
            if "RANGE —" not in text:
                continue  # cover / table of contents
            ranges.append(parse_page(page, page_no))
    ids = [r["id"] for r in ranges]
    if len(set(ids)) != len(ids):
        raise ExtractionError(f"duplicated range ids: {ids}")
    doc = {
        "schemaVersion": 1,
        "source": {
            "id": "kill-tilt-expresso",
            "file": pdf_path.name,
            "title": title,
            "sha256": digest,
            "pages": len(ranges) + 1,
        },
        "ranges": ranges,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(ranges)} ranges written to {out_path}")
    for r in ranges:
        counts: dict[str, int] = {}
        for freqs in r["hands"].values():
            for a in freqs:
                counts[a] = counts.get(a, 0) + 1
        print(f"  p{r['source']['page']:>2} {r['id']:<22} {counts}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ExtractionError as exc:
        print(f"EXTRACTION FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
